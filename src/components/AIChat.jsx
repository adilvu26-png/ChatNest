import { useEffect, useRef, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { useAuth } from '../context/AuthContext'
import { askAI, AI_NAME } from '../services/ai'
import { Send, Trash } from './Icons'
import { Sparkle } from './NavIcons'
import BackButton from './BackButton'

const SUGGEST = ['Tell me a fun fact', 'Help me reply politely to a friend', 'Explain React hooks simply', 'Plan my weekend']

const load = key => { try { return JSON.parse(localStorage.getItem(key)) || [] } catch { return [] } }
const time = at => new Date(at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })

// AI assistant chat. History is kept in this browser only (localStorage), per signed-in user.
export default function AIChat() {
  const { user } = useAuth(); const nav = useNavigate()
  const key = `chatnest-ai:${user.uid}`
  const [msgs, setMsgs] = useState(() => load(key))
  const [text, setText] = useState(''); const [busy, setBusy] = useState(false); const [err, setErr] = useState('')
  const end = useRef(null); const alive = useRef(true)

  useEffect(() => { alive.current = true; return () => { alive.current = false } }, [])
  useEffect(() => { try { localStorage.setItem(key, JSON.stringify(msgs.slice(-100))) } catch { /* storage blocked */ } }, [msgs, key])
  useEffect(() => { end.current?.scrollIntoView({ block: 'end' }) }, [msgs, busy, err])

  const run = async history => {
    setErr(''); setBusy(true)
    try {
      const reply = await askAI(history)
      const m = { id: Date.now() + 'a', role: 'assistant', content: reply, at: Date.now() }
      if (alive.current) setMsgs(a => [...a, m])
      else try { localStorage.setItem(key, JSON.stringify([...history, m].slice(-100))) } catch { /* storage blocked */ }
    } catch (e) {
      if (alive.current) setErr(e.message || 'Something went wrong.')
    } finally {
      if (alive.current) setBusy(false)
    }
  }

  const send = (value = text) => {
    const content = value.trim()
    if (!content || busy) return
    const next = [...msgs, { id: Date.now() + 'u', role: 'user', content, at: Date.now() }]
    setMsgs(next); setText(''); run(next)
  }

  const clear = () => { if (window.confirm('Clear this conversation?')) { setMsgs([]); setErr('') } }

  return (
    <section className="win">
      <header>
        <BackButton onClick={() => nav('/chat')} />
        <span className="avatar ai-avatar"><Sparkle size={20} /></span>
        <span className="grow"><b>{AI_NAME}</b><small>{busy ? 'typing…' : 'AI assistant · always online'}</small></span>
        {!!msgs.length && <button type="button" className="icon-btn danger" aria-label="Clear conversation" title="Clear conversation" onClick={clear}><Trash size={18} /></button>}
      </header>

      <div className="msgs">
        {!msgs.length && (
          <div className="ai-welcome">
            <span className="avatar ai-avatar big"><Sparkle size={30} /></span>
            <h3>Ask {AI_NAME} anything</h3>
            <p className="muted">Questions, ideas, writing help, translations…</p>
            <div className="ai-sugs">{SUGGEST.map(s => <button key={s} type="button" className="ai-sug" onClick={() => send(s)}>{s}</button>)}</div>
          </div>
        )}
        {msgs.map(m => (
          <div key={m.id} className={'msg ' + (m.role === 'user' ? 'mine' : 'theirs')}>
            <p>{m.content}</p>
            <span className="meta">{time(m.at)}</span>
          </div>
        ))}
        {busy && <div className="msg theirs ai-typing" aria-label="AI is typing"><i /><i /><i /></div>}
        {err && (
          <div className="ai-err" role="alert">
            <span>{err}</span>
            {!busy && msgs.length > 0 && msgs[msgs.length - 1].role === 'user' && <button type="button" onClick={() => run(msgs)}>Try again</button>}
          </div>
        )}
        <div ref={end} />
      </div>

      <div className="banner"><span>Replies are generated by AI and may be wrong.</span></div>
      <form className="composer" onSubmit={e => { e.preventDefault(); send() }}>
        <input placeholder={`Message ${AI_NAME}`} value={text} onChange={e => setText(e.target.value)} disabled={busy} maxLength={2000} />
        <button className="send-round" aria-label="Send" disabled={busy || !text.trim()}><Send size={18} /></button>
      </form>
    </section>
  )
}
